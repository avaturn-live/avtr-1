"""Make the paper's sweep figure and the numbers for its text from a `--plan figure` run.

Input: the JSONL file that `run_scripted_sweep.py --plan figure` writes.
Output: a TikZ/pgfplots file with three panels, and a summary on stdout.

    (a) RLC against the measured T_wait, set A (T_pad = 0).
    (b) RLC against the first fragment, set B (T_wait = 20 ms). The agent sends later fragments
        only after admission, so the first fragment is all the speech the admitting step sees.
    (c) ILC against the measured T_wait of the interruption, all turns.

All latencies are wall-clock totals (`t_total_wall`). Uses the standard library only.

Usage:
    python scripts/sweep_figure.py figure.jsonl --tikz avtr1-latency-sweep-tikz.tex
"""

from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path

# Configuration of the run (avtrn-1): T_present, T_future, T_lead, in ms.
TP, TF, LEAD = 200.0, 205.0, 100.0
FLOOR = LEAD + TF
CEILING = FLOOR + TP
SET_B_T_WAIT = 20.0

_HEADER = r"""%% Sec. 5.2 (controlled sweep). MEASURED DATA, generated by avtr-1 scripts/sweep_figure.py
%% from {source} ({n} turns). Do not edit the data tables by hand: run the script again.
%% Needs pgfplots with the groupplots library and the TikZ calc library.
\begin{{tikzpicture}}
\definecolor{{vizblue}}{{HTML}}{{2A78D6}}
\definecolor{{vizink}}{{HTML}}{{3D3D3A}}
\begin{{groupplot}}[
  group style={{group size=3 by 1, horizontal sep=0.75cm}},
  scale only axis, width=3.4cm, height=2.2cm,
  ymin=295, ymax=515, ytick={{305,405,505}},
  tick label style={{font=\scriptsize, color=vizink}}, label style={{font=\scriptsize, color=vizink}},
  title style={{font=\scriptsize, color=vizink, yshift=-1ex}},
  axis line style={{vizink!60}}, tick style={{vizink!60}},
  grid=major, grid style={{vizink!12, line width=0.3pt}},
  every axis plot/.append style={{line width=0.8pt}},
  clip=true,
]
"""

_MEASURED = r"\addplot[only marks, mark=*, mark size=1.1pt, vizblue, fill opacity=0.85] table {"
_PREDICTED = r"\addplot[vizink, dashed, line width=0.6pt] table {"

_FOOTER = r"""\end{groupplot}
%% shared legend below
\matrix[anchor=north, font=\scriptsize, color=vizink, column sep=6pt, inner sep=0pt]
  at ($(group c2r1.south)+(0,-0.95cm)$) {
  \draw[vizink!70, line width=0.6pt] (0,0) -- (0.35,0); & \node[anchor=west]{bound}; &
  \draw[vizink, dashed, line width=0.6pt] (0,0) -- (0.35,0); & \node[anchor=west]{predicted}; &
  \fill[vizblue] (0.17,0) circle (1.1pt); & \node[anchor=west]{measured}; \\
};
\end{tikzpicture}
"""


def _table(head: str, points: list[tuple[float, float]]) -> str:
    body = "\n".join(f"{x:.1f} {y:.1f}" for x, y in sorted(points))
    return f"{head}\n{body}\n}};\n"


def _ms(value: float) -> float:
    return value * 1000.0


def make_tikz(rows: list[dict], source: str) -> str:
    set_a = [r for r in rows if r["config"]["label"] == "A" and r.get("rlc")]
    set_b = [r for r in rows if r["config"]["label"] == "B" and r.get("rlc")]
    ilc = [r for r in rows if r.get("ilc")]

    a_points = [(_ms(r["rlc"]["t_wait"]), _ms(r["rlc"]["t_total_wall"])) for r in set_a]
    b_points = [
        (_ms(r["predicted"]["received_at_admit"]), _ms(r["rlc"]["t_total_wall"])) for r in set_b
    ]
    c_points = [(_ms(r["ilc"]["t_wait"]), _ms(r["ilc"]["t_total_wall"])) for r in ilc]
    phase_line = [(0.0, FLOOR), (TP - 0.1, CEILING - 0.1)]
    b_top = FLOOR + SET_B_T_WAIT
    pad_line = [(SET_B_T_WAIT, b_top + TP - SET_B_T_WAIT), (TP, b_top), (2 * TP, b_top)]

    out = [_HEADER.format(source=source, n=len(rows))]
    out.append(
        "%% (a)\n"
        r"\nextgroupplot[title={(a) RLC, arrival phase}, xmin=0, xmax=200, xtick={0,100,200},"
        "\n"
        r"  xlabel={$T_{\mathrm{wait}}$ (ms), $T_{\mathrm{pad}}=0$}, ylabel={latency (ms)}]"
        "\n"
        r"\draw[vizink!70, line width=0.6pt] (axis cs:0,305) -- (axis cs:200,305) (axis cs:0,505) -- (axis cs:200,505);"
        "\n"
    )
    out.append(_table(_PREDICTED, phase_line))
    out.append(_table(_MEASURED, a_points))
    out.append(
        "%% (b)\n"
        r"\nextgroupplot[title={(b) RLC, first fragment}, xmin=0, xmax=400, xtick={0,200,400},"
        "\n"
        r"  xlabel={first fragment (ms), $T_{\mathrm{wait}}=20$\,ms}]"
        "\n"
        r"\draw[vizink!70, line width=0.6pt] (axis cs:0,305) -- (axis cs:400,305) (axis cs:0,505) -- (axis cs:400,505);"
        "\n"
    )
    out.append(_table(_PREDICTED, pad_line))
    out.append(_table(_MEASURED, b_points))
    out.append(
        r"\draw[vizink!70, line width=0.4pt] (axis cs:200,295) -- (axis cs:200,505);"
        "\n"
        # Labels in the empty corners: above the flat no-padding line, below the padding slope.
        r"\node[font=\tiny, color=vizink, anchor=north] at (axis cs:300,495) {no padding};"
        "\n"
        r"\node[font=\tiny, color=vizink, anchor=south] at (axis cs:85,312) {left padding};"
        "\n"
    )
    out.append(
        "%% (c)\n"
        r"\nextgroupplot[title={(c) ILC, interruption phase}, xmin=0, xmax=200, xtick={0,100,200},"
        "\n"
        r"  xlabel={$T_{\mathrm{wait}}$ (ms)}]"
        "\n"
        r"\draw[vizink!70, line width=0.6pt] (axis cs:0,305) -- (axis cs:200,305) (axis cs:0,505) -- (axis cs:200,505);"
        "\n"
    )
    out.append(_table(_PREDICTED, phase_line))
    out.append(_table(_MEASURED, c_points))
    out.append(_FOOTER)
    return "".join(out)


_V2_HEADER = r"""%% Sec. 5.2 (controlled sweep). MEASURED DATA, generated by avtr-1 scripts/sweep_figure.py
%% from {source}. Do not edit the data tables by hand: run the script again.
%% Needs pgfplots with the groupplots library and the TikZ calc library.
\begin{{tikzpicture}}
\definecolor{{vizblue}}{{HTML}}{{2A78D6}}
\definecolor{{vizorange}}{{HTML}}{{EB6834}}
\definecolor{{vizink}}{{HTML}}{{3D3D3A}}
\begin{{groupplot}}[
  group style={{group size=3 by 1, horizontal sep=1.05cm}},
  scale only axis, width=3.4cm, height=2.2cm,
  tick label style={{font=\scriptsize, color=vizink}}, label style={{font=\scriptsize, color=vizink}},
  title style={{font=\scriptsize, color=vizink, yshift=-1ex}},
  axis line style={{vizink!60}}, tick style={{vizink!60}},
  grid=major, grid style={{vizink!12, line width=0.3pt}},
  every axis plot/.append style={{line width=0.8pt}},
  clip=true,
]
"""

_RLC_MARK = r"\addplot[only marks, mark=*, mark size=1.1pt, vizblue, fill opacity=0.85] table {"
_ILC_MARK = (
    r"\addplot[only marks, mark=triangle*, mark size=1.5pt, vizorange, fill opacity=0.85] table {"
)
_BOUND_LINES = (
    r"\draw[vizink!70, line width=0.6pt] (axis cs:0,305) -- (axis cs:{x},305) "
    r"(axis cs:0,505) -- (axis cs:{x},505);"
    "\n"
)

_V2_FOOTER = r"""\end{groupplot}
%% shared legend below
\matrix[anchor=north, font=\scriptsize, color=vizink, column sep=6pt, inner sep=0pt]
  at ($(group c2r1.south)+(0,-0.95cm)$) {
  \draw[vizink!70, line width=0.6pt] (0,0) -- (0.35,0); & \node[anchor=west]{bound}; &
  \draw[vizink, dashed, line width=0.6pt] (0,0) -- (0.35,0); & \node[anchor=west]{predicted}; &
  \fill[vizblue] (0.17,0) circle (1.1pt); & \node[anchor=west]{RLC}; &
  \fill[vizorange] (0.17,-0.05) -- (0.24,0.07) -- (0.10,0.07) -- cycle; & \node[anchor=west]{ILC}; \\
};
\end{tikzpicture}
"""


def _jitter(i: int, width: float = 0.32) -> float:
    """Deterministic horizontal spread for a strip plot, in [-width, width]."""
    return ((i * 0.6180339887) % 1.0 - 0.5) * 2 * width


def make_tikz_v2(rows: list[dict], bounds: list[list[dict]], source: str) -> str:
    """Two mechanism panels and one error panel.

    (a) RLC and ILC against the measured T_wait (set A, T_pad = 0): the same line, drawn once.
    (b) RLC against the first fragment (set B, T_wait = 20 ms).
    (c) measured - predicted for every RLC and ILC: the sweep, then each bounds run.
    """
    set_a = [r for r in rows if r["config"]["label"] == "A"]
    set_b = [r for r in rows if r["config"]["label"] == "B" and r.get("rlc")]
    rlc_a = [
        (_ms(r["rlc"]["t_wait"]), _ms(r["rlc"]["t_total_wall"])) for r in set_a if r.get("rlc")
    ]
    ilc_all = [
        (_ms(r["ilc"]["t_wait"]), _ms(r["ilc"]["t_total_wall"])) for r in rows if r.get("ilc")
    ]
    b_points = [
        (_ms(r["predicted"]["received_at_admit"]), _ms(r["rlc"]["t_total_wall"])) for r in set_b
    ]
    phase_line = [(0.0, FLOOR), (TP - 0.1, CEILING - 0.1)]
    b_top = FLOOR + SET_B_T_WAIT
    pad_line = [(SET_B_T_WAIT, b_top + TP - SET_B_T_WAIT), (TP, b_top), (2 * TP, b_top)]

    groups = [("sweep", rows)] + [
        (
            {"framewise": "frame-wise", "blockwise": "block-wise", "avtr1": "XXXX-1"}[
                b[0]["timing"]["name"]
            ],
            b,
        )
        for b in bounds
    ]
    err = {"rlc": [], "ilc": []}
    for g, (_, group_rows) in enumerate(groups):
        for i, r in enumerate(group_rows):
            for k, side in (("rlc", -0.18), ("ilc", 0.18)):
                if r.get(k) and k in r["predicted"]:
                    e = _ms(r[k]["t_total_wall"] - r["predicted"][k])
                    err[k].append((g + side + _jitter(i, 0.12), e))
    labels = ",".join(name for name, _ in groups)

    out = [_V2_HEADER.format(source=source)]
    out.append(
        "%% (a)\n"
        r"\nextgroupplot[title={(a) arrival phase}, xmin=0, xmax=200, xtick={0,100,200},"
        r" ymin=295, ymax=515, ytick={305,405,505},"
        "\n"
        r"  xlabel={$T_{\mathrm{wait}}$ (ms), $T_{\mathrm{pad}}=0$}, ylabel={latency (ms)}]"
        "\n"
    )
    out.append(_BOUND_LINES.format(x=200))
    out.append(_table(_PREDICTED, phase_line))
    out.append(_table(_RLC_MARK, rlc_a))
    out.append(_table(_ILC_MARK, ilc_all))
    out.append(
        "%% (b)\n"
        r"\nextgroupplot[title={(b) RLC, first fragment}, xmin=0, xmax=400, xtick={0,200,400},"
        r" ymin=295, ymax=515, ytick={305,405,505},"
        "\n"
        r"  xlabel={first fragment (ms), $T_{\mathrm{wait}}=20$\,ms}]"
        "\n"
    )
    out.append(_BOUND_LINES.format(x=400))
    out.append(_table(_PREDICTED, pad_line))
    out.append(_table(_RLC_MARK, b_points))
    out.append(
        r"\draw[vizink!70, line width=0.4pt] (axis cs:200,295) -- (axis cs:200,505);"
        "\n"
        r"\node[font=\tiny, color=vizink, anchor=north] at (axis cs:300,495) {no padding};"
        "\n"
        r"\node[font=\tiny, color=vizink, anchor=south] at (axis cs:85,312) {left padding};"
        "\n"
    )
    out.append(
        "%% (c)\n"
        rf"\nextgroupplot[title={{(c) measured $-$ predicted}}, xmin=-0.6, xmax={len(groups) - 0.4},"
        r" ymin=-3, ymax=3, ytick={-2,0,2},"
        "\n"
        rf"  xtick={{0,...,{len(groups) - 1}}}, xticklabels={{{labels}}},"
        r" xticklabel style={font=\tiny, rotate=25, anchor=north east}, ylabel={error (ms)}]"
        "\n"
        rf"\draw[vizink, dashed, line width=0.6pt] (axis cs:-0.6,0) -- (axis cs:{len(groups) - 0.4},0);"
        "\n"
    )
    out.append(_table(_RLC_MARK.replace("mark size=1.1pt", "mark size=0.7pt"), err["rlc"]))
    out.append(_table(_ILC_MARK.replace("mark size=1.5pt", "mark size=1.0pt"), err["ilc"]))
    out.append(_V2_FOOTER)
    return "".join(out)


def summarize(rows: list[dict]) -> None:
    global LEAD, FLOOR, CEILING
    if rows and "timing" in rows[0]:  # runs record their timing (T_lead may be overridden)
        LEAD = float(rows[0]["timing"]["lead"])
        FLOOR = LEAD + TF
        CEILING = FLOOR + TP
    errors = [
        _ms(r[k]["t_total_wall"] - r["predicted"][k])
        for r in rows
        for k in ("rlc", "ilc")
        if r.get(k) and k in r["predicted"]
    ]
    set_a = [r for r in rows if r["config"]["label"] == "A"]
    rlc_a = [_ms(r["rlc"]["t_total_wall"]) for r in set_a]
    rlc_all = [_ms(r["rlc"]["t_total_wall"]) for r in rows]
    ilc_all = [_ms(r["ilc"]["t_total_wall"]) for r in rows if r.get("ilc")]
    t_waits = [_ms(r["rlc"]["t_wait"]) for r in rows]
    ilc_waits = [_ms(r["ilc"]["t_wait"]) for r in rows if r.get("ilc")]

    by_phase: dict[float, list[float]] = defaultdict(list)
    for r in set_a:
        by_phase[r["config"]["t_wait"]].append(_ms(r["rlc"]["t_total_wall"]))
    spread = max(max(v) - min(v) for v in by_phase.values())
    sizes = sorted({_ms(r["config"]["fragment"]) for r in set_a})
    inconsistent = sum(
        1 for r in rows for k in ("rlc", "ilc") if r.get(k) and not r[k]["consistent"]
    )
    outside = sum(1 for v in rlc_all + ilc_all if not FLOOR <= v < CEILING + 1)

    print(f"turns: {len(rows)} (set A {len(set_a)}, set B {len(rows) - len(set_a)})")
    print(
        f"wall - prediction, all RLC and ILC: min {min(errors):+.2f} ms, max {max(errors):+.2f} ms, "
        f"max |.| {max(abs(e) for e in errors):.2f} ms"
    )
    print(f"measured T_wait (RLC): {min(t_waits):.1f} .. {max(t_waits):.1f} ms")
    print(f"measured T_wait (ILC): {min(ilc_waits):.1f} .. {max(ilc_waits):.1f} ms")
    print(
        f"RLC, set A: {min(rlc_a):.1f} .. {max(rlc_a):.1f} ms (bound {FLOOR:.0f} .. {CEILING:.0f})"
    )
    print(f"RLC, all: {min(rlc_all):.1f} .. {max(rlc_all):.1f} ms")
    print(f"ILC, all: {min(ilc_all):.1f} .. {max(ilc_all):.1f} ms")
    print(
        f"later fragment sizes {sizes} ms change the RLC (set A, same T_wait) by at most {spread:.2f} ms"
    )
    print(f"turns with inconsistent terms: {inconsistent}, latencies outside the bound: {outside}")


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    p.add_argument("jsonl", type=Path)
    p.add_argument("--tikz", type=Path, help="write the figure to this file")
    p.add_argument(
        "--bounds",
        type=Path,
        nargs="*",
        default=None,
        help="bounds runs (run_scripted_sweep.py --plan bounds): use the layout with an error panel",
    )
    args = p.parse_args()

    rows = [json.loads(line) for line in args.jsonl.read_text().splitlines() if line.strip()]
    summarize(rows)
    if args.tikz and args.bounds is not None:
        bounds = [
            [json.loads(line) for line in b.read_text().splitlines() if line.strip()]
            for b in args.bounds
        ]
        names = ", ".join([args.jsonl.name] + [b.name for b in args.bounds])
        args.tikz.write_text(make_tikz_v2(rows, bounds, names))
        print(f"figure written to {args.tikz}")
    elif args.tikz:
        args.tikz.write_text(make_tikz(rows, args.jsonl.name))
        print(f"figure written to {args.tikz}")


if __name__ == "__main__":
    main()
